`timescale 1ns/1ps

module watchdog_timer_tb;

    // =========================================================
    // TESTBENCH SIGNALS
    // =========================================================

    reg clk;
    reg rst;

    reg enable;
    reg kick;

    reg [7:0] timeout_value;

    wire timeout;

    wire [7:0] counter;


    // =========================================================
    // DUT
    // =========================================================

    watchdog_timer #(
        .WIDTH(8)
    ) dut (

        .clk(clk),
        .rst(rst),

        .enable(enable),
        .kick(kick),

        .timeout_value(timeout_value),

        .timeout(timeout),
        .counter(counter)

    );


    // =========================================================
    // CLOCK
    // =========================================================

    initial begin

        clk = 1'b0;

        forever #5 clk = ~clk;

    end


    // =========================================================
    // WAVEFORM
    // =========================================================

    initial begin

        $dumpfile("watchdog_timer_tb.vcd");

        $dumpvars(0, watchdog_timer_tb);

    end


    // =========================================================
    // MONITOR
    // =========================================================

    initial begin

        $monitor(
            "Time=%0t | RESET=%b | ENABLE=%b | KICK=%b | TIMEOUT_VALUE=%0d | COUNTER=%0d | TIMEOUT=%b",
            $time,
            rst,
            enable,
            kick,
            timeout_value,
            counter,
            timeout
        );

    end


    // =========================================================
    // TEST SEQUENCE
    // =========================================================

    initial begin

        // -----------------------------------------------------
        // INITIAL CONDITIONS
        // -----------------------------------------------------

        rst = 1'b1;

        enable = 1'b0;

        kick = 1'b0;

        timeout_value = 8'd10;


        // -----------------------------------------------------
        // RESET
        // -----------------------------------------------------

        #20;

        rst = 1'b0;

        enable = 1'b1;


        // =====================================================
        // TEST 1: NORMAL COUNTING
        // =====================================================

        $display("");
        $display("========================================");
        $display("TEST 1: NORMAL WATCHDOG COUNTING");
        $display("========================================");

        #60;


        // =====================================================
        // TEST 2: KICK BEFORE TIMEOUT
        // =====================================================

        $display("");
        $display("========================================");
        $display("TEST 2: KICK BEFORE TIMEOUT");
        $display("========================================");

        kick = 1'b1;

        #10;

        kick = 1'b0;

        #50;


        // =====================================================
        // TEST 3: ALLOW TIMEOUT
        // =====================================================

        $display("");
        $display("========================================");
        $display("TEST 3: WATCHDOG TIMEOUT");
        $display("========================================");

        #70;


        // =====================================================
        // TEST 4: KICK AFTER TIMEOUT
        // =====================================================

        $display("");
        $display("========================================");
        $display("TEST 4: RECOVERY AFTER TIMEOUT");
        $display("========================================");

        kick = 1'b1;

        #10;

        kick = 1'b0;

        #20;


        // =====================================================
        // TEST 5: DISABLE WATCHDOG
        // =====================================================

        $display("");
        $display("========================================");
        $display("TEST 5: WATCHDOG DISABLED");
        $display("========================================");

        enable = 1'b0;

        #30;


        // =====================================================
        // TEST COMPLETE
        // =====================================================

        $display("");
        $display("========================================");
        $display("WATCHDOG TIMER TEST COMPLETED");
        $display("========================================");

        $finish;

    end

endmodule