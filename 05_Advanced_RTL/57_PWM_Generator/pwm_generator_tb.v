`timescale 1ns/1ps

module pwm_generator_tb;

    // =========================================================
    // TESTBENCH SIGNALS
    // =========================================================

    reg clk;
    reg rst;
    reg enable;

    reg [7:0] duty_cycle;

    wire pwm_out;


    // =========================================================
    // DUT
    // =========================================================

    pwm_generator #(
        .PERIOD(100)
    ) dut (

        .clk(clk),
        .rst(rst),
        .enable(enable),
        .duty_cycle(duty_cycle),
        .pwm_out(pwm_out)

    );


    // =========================================================
    // CLOCK
    // =========================================================

    initial begin

        clk = 1'b0;

        forever #5 clk = ~clk;

    end


    // =========================================================
    // WAVEFORM
    // =========================================================

    initial begin

        $dumpfile("pwm_generator_tb.vcd");

        $dumpvars(0, pwm_generator_tb);

    end


    // =========================================================
    // MONITOR
    // =========================================================

    initial begin

        $monitor(
            "Time=%0t | RESET=%b | ENABLE=%b | DUTY=%0d | COUNTER=%0d | PWM=%b",
            $time,
            rst,
            enable,
            duty_cycle,
            dut.counter,
            pwm_out
        );

    end


    // =========================================================
    // TEST SEQUENCE
    // =========================================================

    initial begin

        // -----------------------------------------------------
        // INITIAL CONDITIONS
        // -----------------------------------------------------

        rst = 1'b1;

        enable = 1'b0;

        duty_cycle = 8'd0;


        // -----------------------------------------------------
        // RESET
        // -----------------------------------------------------

        #20;

        rst = 1'b0;

        enable = 1'b1;


        // =====================================================
        // TEST 1: 0% DUTY CYCLE
        // =====================================================

        duty_cycle = 8'd0;

        $display("");
        $display("========================================");
        $display("TEST 1: DUTY CYCLE = 0%%");
        $display("========================================");

        #1000;


        // =====================================================
        // TEST 2: 25% DUTY CYCLE
        // =====================================================

        duty_cycle = 8'd25;

        $display("");
        $display("========================================");
        $display("TEST 2: DUTY CYCLE = 25%%");
        $display("========================================");

        #1000;


        // =====================================================
        // TEST 3: 50% DUTY CYCLE
        // =====================================================

        duty_cycle = 8'd50;

        $display("");
        $display("========================================");
        $display("TEST 3: DUTY CYCLE = 50%%");
        $display("========================================");

        #1000;


        // =====================================================
        // TEST 4: 75% DUTY CYCLE
        // =====================================================

        duty_cycle = 8'd75;

        $display("");
        $display("========================================");
        $display("TEST 4: DUTY CYCLE = 75%%");
        $display("========================================");

        #1000;


        // =====================================================
        // TEST 5: 100% DUTY CYCLE
        // =====================================================

        duty_cycle = 8'd100;

        $display("");
        $display("========================================");
        $display("TEST 5: DUTY CYCLE = 100%%");
        $display("========================================");

        #1000;


        // =====================================================
        // TEST 6: DISABLE
        // =====================================================

        enable = 1'b0;

        $display("");
        $display("========================================");
        $display("TEST 6: PWM DISABLED");
        $display("========================================");

        #100;


        // =====================================================
        // COMPLETE
        // =====================================================

        $display("");
        $display("========================================");
        $display("PWM GENERATOR TEST COMPLETED");
        $display("========================================");

        $finish;

    end

endmodule