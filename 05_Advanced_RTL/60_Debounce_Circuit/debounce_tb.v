`timescale 1ns/1ps

module debounce_tb;

    // =========================================================
    // SIGNALS
    // =========================================================

    reg clk;
    reg rst;
    reg enable;

    reg button_in;

    wire button_out;


    // =========================================================
    // DUT
    // =========================================================

    debounce #(
        .COUNT_WIDTH(4),
        .STABLE_COUNT(4)
    ) dut (

        .clk(clk),
        .rst(rst),
        .enable(enable),

        .button_in(button_in),

        .button_out(button_out)

    );


    // =========================================================
    // CLOCK
    // =========================================================

    initial begin

        clk = 1'b0;

        forever #5 clk = ~clk;

    end


    // =========================================================
    // VCD
    // =========================================================

    initial begin

        $dumpfile("debounce_tb.vcd");

        $dumpvars(0, debounce_tb);

    end


    // =========================================================
    // MONITOR
    // =========================================================

    initial begin

        $monitor(
            "Time=%0t | RESET=%b | ENABLE=%b | BUTTON_IN=%b | SYNC=%b | LAST=%b | COUNT=%0d | BUTTON_OUT=%b",
            $time,
            rst,
            enable,
            button_in,
            dut.button_sync,
            dut.button_last,
            dut.stable_counter,
            button_out
        );

    end


    // =========================================================
    // TEST SEQUENCE
    // =========================================================

    initial begin

        // -----------------------------------------------------
        // INITIAL CONDITIONS
        // -----------------------------------------------------

        rst = 1'b1;

        enable = 1'b0;

        button_in = 1'b0;


        // -----------------------------------------------------
        // RESET
        // -----------------------------------------------------

        #20;

        rst = 1'b0;

        enable = 1'b1;


        // =====================================================
        // TEST 1: STABLE LOW
        // =====================================================

        $display("");
        $display("========================================");
        $display("TEST 1: STABLE LOW");
        $display("========================================");

        button_in = 1'b0;

        #60;


        // =====================================================
        // TEST 2: BUTTON BOUNCE
        // =====================================================

        $display("");
        $display("========================================");
        $display("TEST 2: BUTTON BOUNCE");
        $display("========================================");

        button_in = 1'b1;

        #7;

        button_in = 1'b0;

        #6;

        button_in = 1'b1;

        #8;

        button_in = 1'b0;

        #6;

        button_in = 1'b1;

        #7;

        button_in = 1'b0;

        #6;

        button_in = 1'b1;


        // -----------------------------------------------------
        // Wait for stable HIGH
        // -----------------------------------------------------

        #60;


        // =====================================================
        // TEST 3: STABLE HIGH
        // =====================================================

        $display("");
        $display("========================================");
        $display("TEST 3: STABLE HIGH");
        $display("========================================");

        button_in = 1'b1;

        #60;


        // =====================================================
        // TEST 4: BOUNCE BACK TO LOW
        // =====================================================

        $display("");
        $display("========================================");
        $display("TEST 4: BOUNCE BACK TO LOW");
        $display("========================================");

        button_in = 1'b0;

        #7;

        button_in = 1'b1;

        #6;

        button_in = 1'b0;

        #7;

        button_in = 1'b1;

        #6;

        button_in = 1'b0;


        // -----------------------------------------------------
        // Wait for stable LOW
        // -----------------------------------------------------

        #60;


        // =====================================================
        // TEST 5: DISABLE
        // =====================================================

        $display("");
        $display("========================================");
        $display("TEST 5: DISABLE DEBOUNCE");
        $display("========================================");

        enable = 1'b0;

        #30;


        // =====================================================
        // COMPLETE
        // =====================================================

        $display("");
        $display("========================================");
        $display("DEBOUNCE TEST COMPLETED");
        $display("========================================");

        $finish;

    end

endmodule