`timescale 1ns/1ps

module simple_risc_cpu (
    input wire clk,
    input wire rst,

    output reg [7:0] output_data,
    output reg [4:0] pc,
    output reg halted
);

    // =========================================================
    // OPCODES
    // =========================================================

    localparam OP_NOP  = 4'b0000;
    localparam OP_ADD  = 4'b0001;
    localparam OP_SUB  = 4'b0010;
    localparam OP_AND  = 4'b0011;
    localparam OP_OR   = 4'b0100;
    localparam OP_XOR  = 4'b0101;
    localparam OP_ADDI = 4'b0110;
    localparam OP_LDI  = 4'b0111;
    localparam OP_LD   = 4'b1000;
    localparam OP_ST   = 4'b1001;
    localparam OP_BEQZ = 4'b1010;
    localparam OP_JMP  = 4'b1011;
    localparam OP_OUT  = 4'b1100;
    localparam OP_HLT  = 4'b1111;


    // =========================================================
    // REGISTER FILE
    // =========================================================

    reg [7:0] registers [0:7];


    // =========================================================
    // INSTRUCTION MEMORY
    // =========================================================

    reg [15:0] instruction_memory [0:31];


    // =========================================================
    // DATA MEMORY
    // =========================================================

    reg [7:0] data_memory [0:31];


    // =========================================================
    // INTERNAL SIGNALS
    // =========================================================

    reg [15:0] instruction;

    reg [3:0] opcode;

    reg [2:0] rd;

    reg [2:0] rs1;

    reg [2:0] rs2;

    reg [7:0] immediate;

    reg [4:0] address;

    integer i;


    // =========================================================
    // INITIALIZATION
    // =========================================================

    initial begin

        // -----------------------------------------------------
        // Clear registers
        // -----------------------------------------------------

        for (i = 0; i < 8; i = i + 1)
            registers[i] = 8'd0;


        // -----------------------------------------------------
        // Clear data memory
        // -----------------------------------------------------

        for (i = 0; i < 32; i = i + 1)
            data_memory[i] = 8'd0;


        // -----------------------------------------------------
        // Initial data
        // -----------------------------------------------------

        data_memory[0] = 8'd20;


        // -----------------------------------------------------
        // PROGRAM
        // -----------------------------------------------------

        // -----------------------------------------------------
        // 0: LDI R1, 10
        // -----------------------------------------------------

        instruction_memory[0] =
            16'b0111_001_00001010;


        // -----------------------------------------------------
        // 1: LDI R2, 5
        // -----------------------------------------------------

        instruction_memory[1] =
            16'b0111_010_00000101;


        // -----------------------------------------------------
        // 2: ADD R1, R1, R2
        // R1 = 10 + 5 = 15
        // -----------------------------------------------------

        instruction_memory[2] =
            16'b0001_001_001_010_000;


        // -----------------------------------------------------
        // 3: ADDI R1, R1, 3
        // R1 = 15 + 3 = 18
        // -----------------------------------------------------

        instruction_memory[3] =
            16'b0110_001_00110000;


        // -----------------------------------------------------
        // 4: SUB R1, R1, R2
        // R1 = 18 - 5 = 13
        // -----------------------------------------------------

        instruction_memory[4] =
            16'b0010_001_001_010_000;


        // -----------------------------------------------------
        // 5: LDI R3, 20
        // -----------------------------------------------------

        instruction_memory[5] =
            16'b0111_011_00010100;


        // -----------------------------------------------------
        // 6: ST R3, address 1
        // MEM[1] = 20
        // -----------------------------------------------------

        instruction_memory[6] =
            16'b1001_011_00000001;


        // -----------------------------------------------------
        // 7: LD R4, address 0
        // R4 = MEM[0] = 20
        // -----------------------------------------------------

        instruction_memory[7] =
            16'b1000_100_00000000;


        // -----------------------------------------------------
        // 8: OUT R1
        // OUTPUT = 13
        // -----------------------------------------------------

        instruction_memory[8] =
            16'b1100_001_00000000;


        // -----------------------------------------------------
        // 9: HLT
        // -----------------------------------------------------

        instruction_memory[9] =
            16'b1111_000_00000000;


        // -----------------------------------------------------
        // Remaining instructions = NOP
        // -----------------------------------------------------

        instruction_memory[10] = 16'd0;
        instruction_memory[11] = 16'd0;
        instruction_memory[12] = 16'd0;
        instruction_memory[13] = 16'd0;
        instruction_memory[14] = 16'd0;
        instruction_memory[15] = 16'd0;
        instruction_memory[16] = 16'd0;
        instruction_memory[17] = 16'd0;
        instruction_memory[18] = 16'd0;
        instruction_memory[19] = 16'd0;
        instruction_memory[20] = 16'd0;
        instruction_memory[21] = 16'd0;
        instruction_memory[22] = 16'd0;
        instruction_memory[23] = 16'd0;
        instruction_memory[24] = 16'd0;
        instruction_memory[25] = 16'd0;
        instruction_memory[26] = 16'd0;
        instruction_memory[27] = 16'd0;
        instruction_memory[28] = 16'd0;
        instruction_memory[29] = 16'd0;
        instruction_memory[30] = 16'd0;
        instruction_memory[31] = 16'd0;

    end


    // =========================================================
    // INSTRUCTION DECODE
    // =========================================================

    always @(*) begin

        instruction = instruction_memory[pc];

        opcode = instruction[15:12];

        rd = instruction[11:9];

        rs1 = instruction[8:6];

        rs2 = instruction[5:3];

        immediate = instruction[7:0];

        address = instruction[4:0];

    end


    // =========================================================
    // CPU EXECUTION
    // =========================================================

    always @(posedge clk or posedge rst) begin

        if (rst) begin

            pc <= 5'd0;

            output_data <= 8'd0;

            halted <= 1'b0;

        end

        else if (!halted) begin

            case (opcode)

                // =================================================
                // NOP
                // =================================================

                OP_NOP: begin

                    pc <= pc + 1'b1;

                end


                // =================================================
                // ADD
                // =================================================

                OP_ADD: begin

                    registers[rd] <=
                        registers[rs1] + registers[rs2];

                    pc <= pc + 1'b1;

                end


                // =================================================
                // SUB
                // =================================================

                OP_SUB: begin

                    registers[rd] <=
                        registers[rs1] - registers[rs2];

                    pc <= pc + 1'b1;

                end


                // =================================================
                // AND
                // =================================================

                OP_AND: begin

                    registers[rd] <=
                        registers[rs1] & registers[rs2];

                    pc <= pc + 1'b1;

                end


                // =================================================
                // OR
                // =================================================

                OP_OR: begin

                    registers[rd] <=
                        registers[rs1] | registers[rs2];

                    pc <= pc + 1'b1;

                end


                // =================================================
                // XOR
                // =================================================

                OP_XOR: begin

                    registers[rd] <=
                        registers[rs1] ^ registers[rs2];

                    pc <= pc + 1'b1;

                end


                // =================================================
                // ADD IMMEDIATE
                // =================================================

                OP_ADDI: begin

                    registers[rd] <=
                        registers[rs1] + immediate;

                    pc <= pc + 1'b1;

                end


                // =================================================
                // LOAD IMMEDIATE
                // =================================================

                OP_LDI: begin

                    registers[rd] <= immediate;

                    pc <= pc + 1'b1;

                end


                // =================================================
                // LOAD
                // =================================================

                OP_LD: begin

                    registers[rd] <= data_memory[address];

                    pc <= pc + 1'b1;

                end


                // =================================================
                // STORE
                // =================================================

                OP_ST: begin

                    data_memory[address] <= registers[rd];

                    pc <= pc + 1'b1;

                end


                // =================================================
                // BRANCH IF ZERO
                // =================================================

                OP_BEQZ: begin

                    if (registers[rd] == 8'd0)

                        pc <= address;

                    else

                        pc <= pc + 1'b1;

                end


                // =================================================
                // JUMP
                // =================================================

                OP_JMP: begin

                    pc <= address;

                end


                // =================================================
                // OUTPUT
                // =================================================

                OP_OUT: begin

                    output_data <= registers[rd];

                    pc <= pc + 1'b1;

                end


                // =================================================
                // HALT
                // =================================================

                OP_HLT: begin

                    halted <= 1'b1;

                end


                // =================================================
                // DEFAULT
                // =================================================

                default: begin

                    pc <= pc + 1'b1;

                end

            endcase

        end

    end

endmodule